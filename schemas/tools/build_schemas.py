def outputs():
    out = {}
    out["owl/aidcf-core-1.3.ttl"] = build_owl()
    out["jsonld/aidcf-context-1.3.jsonld"] = json.dumps(build_context(), indent=2) + "\n"
    out["shacl/aidcf-shapes-1.3.ttl"] = build_shacl()
    out["json-schema/" + DEFS] = json.dumps(build_defs(), indent=2) + "\n"
    out["json-schema/" + ENV] = json.dumps(build_envelope(), indent=2) + "\n"
    for c in sorted(CLASS_META):
        out["json-schema/" + schema_file(c)] = json.dumps(build_class_schema(c), indent=2) + "\n"
    return out


def main():
    check = "--check" in sys.argv
    outs = outputs()
    stale = [p for p in (ROOT / "json-schema").glob("*.schema.json") if "json-schema/" + p.name not in outs]
    bad = 0
    for rel, text in outs.items():
        p = ROOT / rel
        if check:
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                print("DIFFERS:", rel)
                bad += 1
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
    if check:
        for p in stale:
            print("STALE:", p.name)
        bad += len(stale)
        print("schema set up to date" if not bad else "%d generated file(s) out of date" % bad)
        sys.exit(1 if bad else 0)
    for p in stale:
        p.unlink()
    for f in REQUIRED_SCHEMA_FILES:
        assert (ROOT / "json-schema" / (f + ".schema.json")).exists(), f
    print("wrote %d files; removed %d stale" % (len(outs), len(stale)))


if __name__ == "__main__":
    main()
