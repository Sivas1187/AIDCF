# --------------------------------------------------------------- JSON-LD
def build_context():
    ctx = {"@version": 1.1, "@protected": True, "@vocab": NS,
           "aidcf": NS, "aidcfv": VOCAB_NS, "xsd": XSD, "prov": "http://www.w3.org/ns/prov#",
           "skos": "http://www.w3.org/2004/02/skos/core#", "rdfs": "http://www.w3.org/2000/01/rdf-schema#",
           "id": "@id", "type": "@type"}
    for c in sorted(CLASS_META):
        ctx[c] = "aidcf:" + c
    for pn, p in sorted(P.items()):
        k = p["kind"]
        if k == "ref":
            ctx[pn] = {"@id": "aidcf:" + pn, "@type": "@id"}
        elif k == "reflist":
            ctx[pn] = {"@id": "aidcf:" + pn, "@type": "@id", "@container": "@list"}
        elif k == "date":
            ctx[pn] = {"@id": "aidcf:" + pn, "@type": "xsd:date"}
        elif k == "datetime":
            ctx[pn] = {"@id": "aidcf:" + pn, "@type": "xsd:dateTime"}
        elif k == "json":
            ctx[pn] = {"@id": "aidcf:" + pn, "@type": "@json"}
        elif k == "list":
            ctx[pn] = {"@id": "aidcf:" + pn, "@container": "@list"}
        else:
            ctx[pn] = "aidcf:" + pn
    return {"@context": ctx}


