DEFS = "definitions.schema.json"
ENV = "common-envelope.schema.json"


def prop_schema(pn, many_min=None):
    p = P[pn]
    k = p["kind"]
    if k == "ref":
        item = {"$ref": DEFS + "#/$defs/iri"}
    elif k == "code":
        item = {"$ref": DEFS + "#/$defs/code-" + p["scheme"]}
    elif k == "obj":
        item = {"$ref": DEFS + "#/$defs/obj-" + p["obj"]}
    elif k == "date":
        item = {"$ref": DEFS + "#/$defs/date"}
    elif k == "datetime":
        item = {"$ref": DEFS + "#/$defs/dateTime"}
    elif k == "int":
        item = {"type": "integer"}
    elif k == "num":
        item = {"type": "number"}
    elif k == "bool":
        item = {"type": "boolean"}
    elif k == "json":
        return {"type": "object"}
    elif k == "list":
        return {"type": "array", "minItems": 1, "items": {"type": "string", "minLength": 1}}
    elif k == "reflist":
        return {"type": "array", "minItems": 1, "items": {"$ref": DEFS + "#/$defs/iri"}}
    else:
        item = {"type": "string", "minLength": 1}
    if "pattern" in p:
        item["pattern"] = p["pattern"]
    if "const" in p:
        item = {"const": p["const"]}
    if "minimum" in p:
        item["minimum"] = p["minimum"]
    if "maximum" in p:
        item["maximum"] = p["maximum"]
    if p["many"]:
        s = {"type": "array", "uniqueItems": True, "items": item}
        if many_min:
            s["minItems"] = many_min
        return s
    return item


def build_defs():
    d = {"iri": {"type": "string", "pattern": IRI_PATTERN},
         "date": {"type": "string", "format": "date", "pattern": r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$"},
         "dateTime": {"type": "string", "format": "date-time",
                      "pattern": r"^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]+)?(Z|[+-][0-9]{2}:[0-9]{2})$"}}
    for s, (lab, src, codes) in VOCABS.items():
        d["code-" + s] = {"title": lab, "description": "Controlled vocabulary (%s)." % src, "type": "string",
                          "enum": [c[0] for c in codes]}
    for n, (req, opt) in NESTED.items():
        d["obj-" + n] = {"type": "object", "additionalProperties": False, "required": req,
                         "properties": {pn: prop_schema(pn) for pn in req + opt}}
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": SCHEMA_BASE + DEFS,
            "title": "AIDCF 1.3 shared definitions",
            "description": "Shared value definitions: IRIs, dates, controlled vocabularies (codes read from registries/vocabularies/*.csv where bound) and nested structures. Not a record schema.",
            "$defs": d}


def build_envelope():
    props = {"@context": {"description": "JSON-LD context reference when the record is serialised standalone."},
             "id": {"$ref": DEFS + "#/$defs/iri"}, "type": {"type": "string", "pattern": "^[A-Z][A-Za-z]+$"}}
    for pn in ENVELOPE_REQUIRED[2:] + ENVELOPE_OPTIONAL:
        props[pn] = prop_schema(pn)
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": SCHEMA_BASE + ENV,
            "title": "AIDCF common object envelope (AIDCF-014 v1.1 section 8; AIDCF-016)",
            "description": "Envelope carried by every AIDCF record. Concrete record schemas reference these property "
                           "definitions and repeat the required list, so that each concrete schema can be closed with "
                           "additionalProperties false. reviewState is required for assertion-bearing classes and scope for "
                           "assessable classes; distributionControlRef is required when classification is above INTERNAL.",
            "type": "object", "additionalProperties": False, "required": ENVELOPE_REQUIRED,
            "properties": props,
            "if": {"properties": {"classification": {"enum": ["CLIENT_RESTRICTED", "CONFIDENTIAL", "HIGHLY_RESTRICTED"]}}, "required": ["classification"]},
            "then": {"required": ["distributionControlRef"]}}


def build_class_schema(c):
    req, opt, mins = R[c]
    props = {"@context": {"$ref": ENV + "#/properties/@context"},
             "id": {"$ref": ENV + "#/properties/id"}, "type": {"const": c}}
    for pn in ENVELOPE_REQUIRED[2:] + ENVELOPE_OPTIONAL:
        props[pn] = {"$ref": ENV + "#/properties/" + pn}
    for pn in req + opt:
        props[pn] = prop_schema(pn, mins.get(pn))
    m = CLASS_META[c]
    out = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": SCHEMA_BASE + schema_file(c),
           "title": "AIDCF %s (%s)" % (m["label"], c), "description": m["definition"],
           "x-aidcf-class": NS + c, "x-aidcf-semantic-owner": m["owner"], "x-aidcf-registration": m["group"],
           "type": "object", "additionalProperties": False,
           "required": required_fields(c), "properties": props,
           "if": {"properties": {"classification": {"enum": ["CLIENT_RESTRICTED", "CONFIDENTIAL", "HIGHLY_RESTRICTED"]}}, "required": ["classification"]},
           "then": {"required": ["distributionControlRef"]}}
    return out


# ------------------------------------------------------------------ SHACL
def pshape(pn, required, many_min=None, path=None):
    p = P[pn]
    k = p["kind"]
    parts = ["sh:path %s" % (path or "aidcf:%s" % pn)]
    # A required multi-valued property may be an empty JSON array; RDF cannot distinguish an empty array from an absent
    # property, so SHACL enforces only explicit minimum counts on multi-valued properties (AIDCF-016 section 8.3).
    mn = many_min if many_min is not None else (1 if required and not (p["many"] or k in ("list", "reflist")) else 0)
    if mn:
        parts.append("sh:minCount %d" % mn)
    if not p["many"] and k not in ("list", "reflist"):
        parts.append("sh:maxCount 1")
    if k == "ref":
        parts.append("sh:nodeKind sh:IRI")
        rng = p.get("range")
        if rng and len(rng) == 1:
            parts.append("sh:class aidcf:%s" % rng[0])
        elif rng:
            parts.append("sh:or ( %s )" % " ".join("[ sh:class aidcf:%s ]" % r for r in rng))
    elif k == "code":
        parts.append("sh:datatype xsd:string")
        parts.append("sh:in ( %s )" % " ".join(lit(c[0]) for c in VOCABS[p["scheme"]][2]))
    elif k in ("str", "text"):
        parts.append("sh:datatype xsd:string")
        parts.append("sh:minLength 1")
        if "pattern" in p:
            parts.append("sh:pattern %s" % lit(p["pattern"]))
        if "const" in p:
            parts.append("sh:hasValue %s" % lit(p["const"]))
    elif k == "date":
        parts.append("sh:datatype xsd:date")
    elif k == "datetime":
        parts.append("sh:datatype xsd:dateTime")
    elif k == "int":
        parts.append("sh:datatype xsd:integer")
        if "minimum" in p:
            parts.append("sh:minInclusive %d" % p["minimum"])
        if "maximum" in p:
            parts.append("sh:maxInclusive %d" % p["maximum"])
    elif k == "num":
        parts.append("sh:node aidcf:NumberShape")
        if "minimum" in p:
            parts.append("sh:minInclusive %d" % p["minimum"])
        if "maximum" in p:
            parts.append("sh:maxInclusive %d" % p["maximum"])
    elif k == "bool":
        parts.append("sh:datatype xsd:boolean")
    elif k == "json":
        parts.append("sh:datatype rdf:JSON")
    elif k == "obj":
        parts.append("sh:nodeKind sh:BlankNodeOrIRI")
        parts.append("sh:node aidcf:%sShape" % p["obj"])
    elif k in ("list", "reflist"):
        parts.append("sh:nodeKind sh:BlankNodeOrIRI")
    return "  sh:property [ %s ]" % " ; ".join(parts)


def classes_or(cs):
    return "( %s )" % " ".join("[ sh:class aidcf:%s ]" % c for c in cs)


def build_shacl():
    L = []
    a = L.append
    a("# AIDCF SHACL shapes 1.3 (AIDCF-016). GENERATED by schemas/tools/build_schemas.py; do not edit by hand.")
    a("# Validate with the ontology graph mixed in (pyshacl ont_graph) so that subclass targets and relationshipCode lookups resolve.")
    a("@prefix aidcf: <%s> ." % NS)
    a("@prefix sh: <http://www.w3.org/ns/shacl#> .")
    a("@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .")
    a("@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .")
    a("@prefix xsd: <%s> ." % XSD)
    a("@prefix owl: <http://www.w3.org/2002/07/owl#> .")
    a("")
    a("<%s> a owl:Ontology ; owl:imports <%s> ;" % (SHAPES_IRI, VERSION_IRI))
    a('  rdfs:label "AIDCF SHACL shapes 1.3"@en ;')
    a("  sh:declare [ sh:prefix \"aidcf\" ; sh:namespace \"%s\"^^xsd:anyURI ] ;" % NS)
    a("  sh:declare [ sh:prefix \"rdf\" ; sh:namespace \"http://www.w3.org/1999/02/22-rdf-syntax-ns#\"^^xsd:anyURI ] ;")
    a("  sh:declare [ sh:prefix \"xsd\" ; sh:namespace \"%s\"^^xsd:anyURI ] ." % XSD)
    a("")
    a("aidcf:NumberShape a sh:NodeShape ; sh:or ( [ sh:datatype xsd:integer ] [ sh:datatype xsd:decimal ] [ sh:datatype xsd:double ] ) .")
    a("")
    a("# ---------------- Envelope (AIDCF-014 section 8), every concrete class")
    a("aidcf:EnvelopeShape a sh:NodeShape ;")
    a("  rdfs:comment \"Common object envelope (AIDCF-014 section 8).\"@en ;")
    a("  sh:targetClass %s ;" % " , ".join("aidcf:" + c for c in sorted(CLASS_META)))
    a("  sh:nodeKind sh:IRI ;")
    env = [pshape(pn, True) for pn in ENVELOPE_REQUIRED[2:]] + [pshape(pn, False) for pn in ENVELOPE_OPTIONAL]
    a(" ;\n".join(env) + " .")
    a("aidcf:AssertionBearingShape a sh:NodeShape ; rdfs:comment \"reviewState is mandatory for assertion-bearing classes (AIDCF-014 section 8).\"@en ;")
    a("  sh:targetClass %s ;" % " , ".join("aidcf:" + c for c in ASSERTION_BEARING))
    a("  sh:property [ sh:path aidcf:reviewState ; sh:minCount 1 ] .")
