def lit(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def scheme_iri(s):
    return VOCAB_NS + kebab(s)


def concept_iri(s, code):
    return scheme_iri(s) + "/" + code


def card_str(t):
    return "%d..%s" % (t[0], "*" if t[1] is None else t[1])


def union(cs):
    if len(cs) == 1:
        return "aidcf:%s" % cs[0]
    return "[ a owl:Class ; owl:unionOf ( %s ) ]" % " ".join("aidcf:%s" % c for c in cs)


