    a("  sh:targetClass %s ;" % " , ".join("aidcf:" + c for c in ASSESSABLE))
    a("  sh:property [ sh:path aidcf:scope ; sh:minCount 1 ] .")
    a("")
    a("# ---------------- Nested structures")
    for n, (req, opt) in NESTED.items():
        a("aidcf:%sShape a sh:NodeShape ;" % n)
        a(" ;\n".join([pshape(pn, True) for pn in req] + [pshape(pn, False) for pn in opt]) + " .")
