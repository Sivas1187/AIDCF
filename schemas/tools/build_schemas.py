"""Generate the AIDCF 1.3 canonical schema set from aidcf_model.py.

Usage: python -B schemas/tools/build_schemas.py [--check]

Writes schemas/owl/aidcf-core-1.3.ttl, schemas/jsonld/aidcf-context-1.3.jsonld,
schemas/shacl/aidcf-shapes-1.3.ttl and schemas/json-schema/*.schema.json, and removes
JSON Schema files that the model no longer generates. Controlled-vocabulary codes are
read from registries/vocabularies/*.csv. With --check, regenerates in memory and exits 1
if any committed file differs or a stale file exists. Output is deterministic.
"""
