def spt(name, target_select, prop, message, comment):
    """Shape with a SPARQL-based target (one query) and a core minCount constraint (fast in pyshacl)."""
    return ("aidcf:%s a sh:NodeShape ;\n"
            "  sh:target [ a sh:SPARQLTarget ; sh:prefixes <%s> ; sh:select \"\"\"%s\"\"\" ] ;\n"
            "  rdfs:comment %s@en ;\n"
            "  sh:property [ sh:path aidcf:%s ; sh:minCount 1 ; sh:message %s ] .\n") % (name, SHAPES_IRI, target_select.strip(), lit(comment), prop, lit(message))


def sp(name, target, message, select, comment):
    tgt = ("sh:targetClass aidcf:%s" % target) if not target.startswith("sh:") else target
    return ("aidcf:%s a sh:NodeShape ; %s ;\n"
            "  rdfs:comment %s@en ;\n"
            "  sh:sparql [ a sh:SPARQLConstraint ; sh:message %s ; sh:prefixes <%s> ;\n"
            "    sh:select \"\"\"%s\"\"\" ] .\n") % (name, tgt, lit(comment), lit(message), SHAPES_IRI, select.strip())


# SHACL-SPARQL forbids VALUES (SHACL section 5.3.1), so code ranks are computed with nested IF expressions.
def _ifmap(var, pairs, default):
    e = str(default)
    for k, v in reversed(pairs):
        e = 'IF(%s = "%s", %s, %s)' % (var, k, v, e)
    return e
def rank(var):
    # AIDCF-010 order: NOT_ASSURED is the most restrictive state, below INCONCLUSIVE (model DECISION_RANK).
    return _ifmap(var, sorted(M.DECISION_RANK.items(), key=lambda kv: -kv[1]), 0)
def crank(var):
    return _ifmap(var, [("PUBLIC", 0), ("INTERNAL", 1), ("CLIENT_RESTRICTED", 2), ("CONFIDENTIAL", 3), ("HIGHLY_RESTRICTED", 4)], 0)
def claimrank(var):
    return _ifmap(var, [("DESIGN", 2), ("IMPLEMENTATION", 3), ("OPERATION", 4), ("EFFECTIVENESS", 5), ("RESILIENCE", 5)], 0)
def minal(var):
    return _ifmap(var, [("DESIGN", '"AL2"'), ("IMPLEMENTATION", '"AL3"'), ("OPERATION", '"AL4"'), ("EFFECTIVENESS", '"AL5"'), ("RESILIENCE", '"AL5"')], '""')

